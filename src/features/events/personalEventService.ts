import {mockPersonalEvents} from '../../mocks'
import type {LocalDateTime} from '../../types/common'
import type {PersonalEvent, PersonalEventCreate, PersonalEventUpdate} from '../../types/schedule'

/** Simulated network latency of the mock, so loading states are visible. */
const MOCK_LATENCY_MS = 400

// In-memory copy: fixtures stay untouched, created events live until page reload.
let storedEvents: PersonalEvent[] = []
let nextId = Math.max(0, ...mockPersonalEvents.map((event) => event.id)) + 1000

function delay(ms: number) {
    return new Promise((resolve) => setTimeout(resolve, ms))
}

/**
 * Personal-event data access (mock implementation of `POST` / `PUT /personal-event`).
 *
 * TODO(FE-21): add `remove` and the HTTP variant once `apiClient` exists.
 */
export const personalEventService = {
    /** Creates a personal event and resolves with the stored DTO. */
    async create(data: PersonalEventCreate): Promise<PersonalEvent> {
        await delay(MOCK_LATENCY_MS)

        const created: PersonalEvent = {
            id: nextId++,
            userId: data.userId,
            name: data.name,
            location: data.location ?? null,
            description: data.description ?? null,
            startsAt: data.startsAt,
            endsAt: data.endsAt,
        }
        storedEvents = [...storedEvents, created]

        return structuredClone(created)
    },

    /**
     * Replaces the editable fields of an existing personal event and resolves with the
     * stored DTO. Rejects when the event does not exist (nothing is changed then).
     */
    async update(data: PersonalEventUpdate): Promise<PersonalEvent> {
        await delay(MOCK_LATENCY_MS)

        const current = storedEvents.find((event) => event.id === data.id)
        if (!current) throw new Error(`Personal event ${data.id} not found`)

        const updated: PersonalEvent = {
            ...current,
            name: data.name,
            location: data.location ?? null,
            description: data.description ?? null,
            startsAt: data.startsAt,
            endsAt: data.endsAt,
        }
        storedEvents = storedEvents.map((event) => (event.id === data.id ? updated : event))

        return structuredClone(updated)
    },

    /**
     * True when the event exists in the store, i.e. it was created by the user and can be
     * edited. The sample personal events generated by the mock schedule are read-only.
     */
    isEditable(eventId: number): boolean {
        return storedEvents.some((event) => event.id === eventId)
    },

    /**
     * Events created in this session that start inside `[from, to)`.
     * Used by the mock schedule service to merge them into the calendar.
     */
    listCreatedInRange(userId: number, from: LocalDateTime, to: LocalDateTime): PersonalEvent[] {
        return structuredClone(
            storedEvents.filter(
                (event) =>
                    event.userId === userId &&
                    event.startsAt >= from &&
                    event.startsAt < to,
            ),
        )
    },
}
